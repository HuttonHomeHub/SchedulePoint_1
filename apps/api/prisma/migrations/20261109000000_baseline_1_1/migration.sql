-- SchedulePoint 1.1 baseline (ADR-0215).
--
-- This one migration builds, from an EMPTY database, the schema that the 84 migrations of
-- api-v1.0.0 built (20260709142606_add_identity_tables … 20261108120000_total_float_minutes), plus
-- only the tidy listed in docs/specs/fresh-start-1-1/schema-design.md §3 (ADR-0215 D1). That
-- history is not lost: it is the git tag api-v1.0.0, and every "was:" line below names the legacy
-- migration an object came from, which is where its reasoning and any recorded measurement (the
-- docs/DATABASE.md "measure before adding an index" rule) still live.
--
-- It only ever runs on an empty database. A database built by 1.0 or earlier is from another
-- generation and is refused, never migrated (ADR-0215; fresh database required).
--
-- Layout:
--   1. btree_gist, first, because the three EXCLUDE constraints in part 3 need it.
--   2. GENERATED: `prisma migrate diff --from-empty --to-schema-datamodel prisma/schema.prisma
--      --script` (Prisma 6), verbatim except three marked hand edits adding NULLS NOT DISTINCT.
--      Tables, enums, declared indexes and foreign keys.
--   3. HAND-WRITTEN: every object Prisma cannot express, grouped by table: CHECK constraints
--      (several fail-closed CASE … ELSE false), partial indexes (soft-delete-scoped uniques and
--      partial FK-check indexes) and EXCLUDE constraints. The SQL is the catalogue's own rendering
--      (pg_get_constraintdef / pg_indexes) of the object the legacy chain left, so it is equal by
--      construction; the reason for each is on its model in schema.prisma and in the cited
--      migration. None is declared in schema.prisma (TECH_DEBT #54).
--   4. HAND-WRITTEN: the audit_events append-only function and triggers, verbatim from
--      20260803170000_audit_events, with ENABLE ALWAYS so a session_replication_role = replica
--      session cannot bypass them (ADR-0072, ADR-0085 D1).
--
-- Proof of equivalence: docs/specs/fresh-start-1-1/schema-design.md, "M2-T1 equivalence proof" (a
-- catalogue comparison against the api-v1.0.0 chain, no differences), and its "M3 tidy" entries: the
-- chain plus the schema design's §3 tidy, as an executable allow-list, equals this file. Every object
-- the tidy changed says so on its "was:" line. Plain CHECKs, no NOT VALID,
-- no CONCURRENTLY, no INSERT: the file runs in one transaction on empty tables.

